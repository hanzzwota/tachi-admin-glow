alter table public.deposits
  add column if not exists transaction_number text,
  add column if not exists submitted_at timestamptz,
  add column if not exists updated_at timestamptz,
  add column if not exists approved_at timestamptz,
  add column if not exists rejected_at timestamptz,
  add column if not exists processed_by_admin_id uuid references public.profiles(id) on delete set null;

update public.deposits
set transaction_number = 'TRX-' || to_char(coalesce(created_at, now()) at time zone 'Asia/Jakarta', 'YYYYMMDD') || '-' || upper(substr(replace(id::text, '-', ''), 1, 8))
where transaction_number is null or btrim(transaction_number) = '';

update public.deposits
set submitted_at = coalesce(submitted_at, created_at),
    updated_at = coalesce(updated_at, coalesce(verified_at, created_at));

alter table public.deposits alter column transaction_number set not null;
create unique index if not exists deposits_transaction_number_uidx on public.deposits(transaction_number);
create index if not exists deposits_submitted_at_idx on public.deposits(submitted_at desc);

create table if not exists public.transaction_status_logs (
  id bigint generated by default as identity primary key,
  transaction_id uuid not null references public.deposits(id) on delete cascade,
  previous_status text,
  new_status text not null,
  rejection_reason text,
  admin_id uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists transaction_status_logs_transaction_idx on public.transaction_status_logs(transaction_id, created_at desc);

create table if not exists public.user_earnings_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  transaction_id uuid not null unique references public.deposits(id) on delete cascade,
  amount bigint not null check (amount >= 0),
  transaction_type text not null default 'deposit_approval',
  created_at timestamptz not null default now()
);
create index if not exists user_earnings_history_user_idx on public.user_earnings_history(user_id, created_at desc);

create or replace function public.approve_deposit_atomic(p_deposit_id uuid, p_admin_id uuid)
returns table(ok boolean, earned bigint, error_code text)
language plpgsql
security definer
set search_path = public
as $$
declare
  d public.deposits%rowtype;
  accepted bigint;
  amount bigint;
begin
  select * into d from public.deposits where id = p_deposit_id for update;
  if not found then return query select false, 0::bigint, 'not_found'; return; end if;
  if d.status <> 'pending' then return query select false, 0::bigint, 'already_processed'; return; end if;
  accepted := coalesce(jsonb_array_length(d.emails), 0);
  amount := coalesce(d.rate, 0) * accepted;
  update public.deposits
  set status = 'diterima', accepted_count = accepted, accepted_emails = d.emails,
      earned = amount, verified_at = now(), approved_at = now(), updated_at = now(),
      processed_by_admin_id = p_admin_id
  where id = p_deposit_id;
  insert into public.user_earnings_history(user_id, transaction_id, amount)
  values (d.user_id, d.id, amount)
  on conflict (transaction_id) do nothing;
  if found then
    update public.profiles set balance = balance + amount where id = d.user_id;
  end if;
  insert into public.transaction_status_logs(transaction_id, previous_status, new_status, admin_id)
  values (d.id, d.status, 'diterima', p_admin_id);
  return query select true, amount, null::text;
end;
$$;

create or replace function public.reject_deposit_atomic(p_deposit_id uuid, p_admin_id uuid, p_reason text)
returns table(ok boolean, error_code text)
language plpgsql
security definer
set search_path = public
as $$
declare old_status text;
begin
  if p_reason is null or btrim(p_reason) = '' then return query select false, 'reason_required'; return; end if;
  select status into old_status from public.deposits where id = p_deposit_id for update;
  if old_status is null then return query select false, 'not_found'; return; end if;
  if old_status <> 'pending' then return query select false, 'already_processed'; return; end if;
  update public.deposits
  set status = 'ditolak', reason = p_reason, rejected_at = now(), verified_at = now(), updated_at = now(), processed_by_admin_id = p_admin_id
  where id = p_deposit_id;
  insert into public.transaction_status_logs(transaction_id, previous_status, new_status, rejection_reason, admin_id)
  values (p_deposit_id, old_status, 'ditolak', p_reason, p_admin_id);
  return query select true, null::text;
end;
$$;

grant execute on function public.approve_deposit_atomic(uuid, uuid) to service_role;
grant execute on function public.reject_deposit_atomic(uuid, uuid, text) to service_role;
